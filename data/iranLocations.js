export function getProvinceNames() {
  return IRAN_LOCATIONS.map((item) => item.province);
}

export function getCitiesByProvince(provinceName) {
  const row = IRAN_LOCATIONS.find((item) => item.province === provinceName);
  return row?.cities || [];
}

export function findProvinceByCity(cityName) {
  if (!cityName) return "";
  const normalized = cityName.trim();
  for (const item of IRAN_LOCATIONS) {
    if (item.cities.includes(normalized)) return item.province;
  }
  return "";
}

export function guessLocationFromLegacyAddress(address = "") {
  const text = String(address || "").trim();
  if (!text) return { province: "", city: "", detail: "" };

  for (const item of IRAN_LOCATIONS) {
    if (text.startsWith(item.province)) {
      const rest = text.slice(item.province.length).replace(/^[،,\s]+/, "");
      for (const city of item.cities) {
        if (rest.startsWith(city)) {
          const detail = rest.slice(city.length).replace(/^[،,\s]+/, "");
          return { province: item.province, city, detail: detail || text };
        }
      }
      return { province: item.province, city: "", detail: rest || text };
    }
    for (const city of item.cities) {
      if (text.startsWith(city)) {
        const detail = text.slice(city.length).replace(/^[،,\s]+/, "");
        return { province: item.province, city, detail: detail || text };
      }
    }
  }

  return { province: "", city: "", detail: text };
}
